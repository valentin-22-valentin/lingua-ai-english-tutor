-- Existing projects: both scripts are additive; historical data is not deleted.
BEGIN;
CREATE TABLE IF NOT EXISTS public.languages(code text PRIMARY KEY,name_en text NOT NULL);
INSERT INTO public.languages VALUES ('en','English'),('hu','Hungarian'),('ro','Romanian'),
 ('es','Spanish'),('fr','French'),('de','German') ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS public.profiles(
 id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
 username text NOT NULL, native_lang_code text NOT NULL DEFAULT 'hu' REFERENCES languages(code),
 target_lang_code text NOT NULL DEFAULT 'en' CHECK(target_lang_code='en'),
 app_lang_code text NOT NULL DEFAULT 'hu' REFERENCES languages(code),current_level text,
 created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS public.chapters(
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,target_lang_code text NOT NULL DEFAULT 'en',
 level text NOT NULL,title text NOT NULL,order_index integer NOT NULL);
CREATE TABLE IF NOT EXISTS public.lessons(
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,chapter_id integer NOT NULL REFERENCES chapters(id),
 title text NOT NULL,lesson_type text NOT NULL DEFAULT 'interactive',system_prompt text NOT NULL,
 passing_score integer NOT NULL DEFAULT 80 CHECK(passing_score BETWEEN 0 AND 100),
 order_index integer NOT NULL,is_level_exam boolean NOT NULL DEFAULT false);
CREATE TABLE IF NOT EXISTS public.chat_sessions(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),profile_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
 lesson_id integer NOT NULL REFERENCES lessons(id),status text NOT NULL DEFAULT 'active',
 revision integer NOT NULL DEFAULT 0,started_at timestamptz NOT NULL DEFAULT now(),ended_at timestamptz);
CREATE TABLE IF NOT EXISTS public.messages(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),session_id uuid NOT NULL REFERENCES chat_sessions(id) ON DELETE CASCADE,
 role text NOT NULL CHECK(role IN ('user','assistant')),content text NOT NULL,created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS public.tutor_turns(
 profile_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,request_id uuid NOT NULL,
 session_id uuid NOT NULL REFERENCES chat_sessions(id) ON DELETE CASCADE,input_text text,result jsonb NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),PRIMARY KEY(profile_id,request_id));
CREATE TABLE IF NOT EXISTS public.user_progress(
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,profile_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
 lesson_id integer NOT NULL REFERENCES lessons(id),score integer,passed boolean NOT NULL DEFAULT false,
 completed_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS public.user_mistakes(
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,profile_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
 target_lang_code text NOT NULL DEFAULT 'en',wrong_sentence text NOT NULL,corrected_sentence text NOT NULL,
 grammar_rule text NOT NULL,asked_again boolean NOT NULL DEFAULT false,review_count integer NOT NULL DEFAULT 0,
 mastered boolean NOT NULL DEFAULT false,next_review_at timestamptz NOT NULL DEFAULT now(),
 last_reviewed_at timestamptz,created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS public.journal_entries(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),profile_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
 request_id uuid NOT NULL,content text NOT NULL CHECK(length(content) BETWEEN 1 AND 1200),
 language_code text NOT NULL DEFAULT 'en' REFERENCES languages(code),feedback jsonb NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),UNIQUE(profile_id,request_id));
CREATE TABLE IF NOT EXISTS public.journal_discussions(
 profile_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,request_id uuid NOT NULL,
 entry_id uuid NOT NULL REFERENCES journal_entries(id) ON DELETE CASCADE,message text NOT NULL,
 text text NOT NULL,created_at timestamptz NOT NULL DEFAULT now(),PRIMARY KEY(profile_id,request_id));
CREATE TABLE IF NOT EXISTS public.schema_releases(id integer PRIMARY KEY,applied_at timestamptz NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS messages_session_date ON messages(session_id,created_at,id);
CREATE INDEX IF NOT EXISTS sessions_profile_date ON chat_sessions(profile_id,started_at DESC,id);
CREATE INDEX IF NOT EXISTS turns_session_date ON tutor_turns(session_id,created_at);
CREATE INDEX IF NOT EXISTS mistakes_due ON user_mistakes(profile_id,next_review_at) WHERE NOT mastered;
CREATE INDEX IF NOT EXISTS journal_profile_date ON journal_entries(profile_id,created_at DESC);
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['languages','profiles','chapters','lessons','chat_sessions','messages',
  'tutor_turns','user_progress','user_mistakes','journal_entries','journal_discussions','schema_releases'] LOOP
  EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',t);
  EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC,anon,authenticated',t);
  EXECUTE format('GRANT ALL ON public.%I TO service_role',t);
 END LOOP;
END $$;
GRANT USAGE,SELECT ON SEQUENCE chapters_id_seq,lessons_id_seq,user_progress_id_seq,user_mistakes_id_seq TO service_role;
COMMIT;
