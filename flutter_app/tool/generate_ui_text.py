"""Compile six JSON resources to synchronous Dart constants.

Run from any directory: python flutter_app/tool/generate_ui_text.py
JSON is the editable source; no asynchronous translation loading or network call
is needed while rendering authentication or error states.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CODES = ('hu', 'en', 'ro', 'es', 'fr', 'de')
resources = {
    code: json.loads((ROOT / 'lib/l10n' / f'app_{code}.json').read_text(encoding='utf-8'))
    for code in CODES
}
baseline = resources['en']
for code, resource in resources.items():
    if resource.keys() != baseline.keys():
        raise ValueError(f'{code}: missing or extra translation keys')
    for key, value in resource.items():
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f'{code}.{key}: empty translation')
        if set(re.findall(r'\{(\w+)\}', value)) != set(re.findall(r'\{(\w+)\}', baseline[key])):
            raise ValueError(f'{code}.{key}: placeholder mismatch')

compiled = json.dumps(resources, ensure_ascii=False, indent=2).replace('$', r'\$')
(ROOT / 'lib/ui_text_data.dart').write_text(
    '// Generated by tool/generate_ui_text.py from lib/l10n/app_*.json.\n'
    '// Edit the JSON resources and regenerate; do not edit this file manually.\n'
    'const Map<String, Map<String, String>> uiTranslations = ' + compiled + ';\n',
    encoding='utf-8',
)
print(f'Generated {len(baseline)} messages in {len(CODES)} languages.')
